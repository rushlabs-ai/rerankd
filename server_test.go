// fakeOllama answers /api/show from a name->modelfile map and streams /api/chat.
type fakeOllama struct {
	*httptest.Server
	models  map[string]string // name -> blob path
	formats map[string]string
	release chan struct{}
}

func newFakeOllama(t *testing.T) *fakeOllama {
	f := &fakeOllama{models: map[string]string{}, formats: map[string]string{}, release: make(chan struct{})}
	mux := http.NewServeMux()
	mux.HandleFunc("POST /api/show", func(w http.ResponseWriter, r *http.Request) {
		var req struct{ Model string }
		_ = json.NewDecoder(r.Body).Decode(&req)
		path, ok := f.models[req.Model]
		if !ok {
			w.WriteHeader(http.StatusNotFound)
			fmt.Fprintf(w, `{"error":"model '%s' not found"}`, req.Model)
			return
		}
		format := f.formats[req.Model]
		if format == "" {
			format = "gguf"
		}
		mf := "# Modelfile generated by \"ollama show\"\n# To build a new Modelfile based on this, replace FROM with:\n# FROM " +
			req.Model + "\n\nFROM " + path + "\nTEMPLATE {{ .Prompt }}\n"
		_ = json.NewEncoder(w).Encode(map[string]any{"modelfile": mf, "details": map[string]string{"format": format}})
	})
	mux.HandleFunc("GET /api/tags", func(w http.ResponseWriter, r *http.Request) {
		_ = json.NewEncoder(w).Encode(map[string]any{"models": []any{}, "host": r.Host})
	})
	mux.HandleFunc("POST /api/chat", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/x-ndjson")
		fmt.Fprintln(w, `{"message":{"content":"Hel"},"done":false}`)
		w.(http.Flusher).Flush()
		select { // the second chunk waits until the client has seen the first
		case <-f.release:
		case <-time.After(5 * time.Second):
		}
		fmt.Fprintln(w, `{"message":{"content":"lo"},"done":true}`)
	})
	f.Server = httptest.NewServer(mux)
	t.Cleanup(f.Close)
	return f
}

// fakeEngine mimics llama-server's /v1/rerank: scores are the count of query words in the document.
func fakeEngineHandler(calls *atomic.Int32) http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /health", func(w http.ResponseWriter, r *http.Request) { fmt.Fprint(w, `{"status":"ok"}`) })
	mux.HandleFunc("POST /v1/rerank", func(w http.ResponseWriter, r *http.Request) {
		if calls != nil {
			calls.Add(1)
		}
		var req struct {
			Query     string   `json:"query"`
			Documents []string `json:"documents"`
			TopN      int      `json:"top_n"`
		}
		_ = json.NewDecoder(r.Body).Decode(&req)
		if strings.Contains(req.Query, "too long") {
			w.WriteHeader(http.StatusBadRequest)
			fmt.Fprint(w, `{"error":{"code":400,"message":"input is too large to process. increase the physical batch size","type":"invalid_request_error"}}`)
			return
		}
		type res struct {
			Index int     `json:"index"`
			Score float64 `json:"relevance_score"`
		}
		var out []res
		for i, d := range req.Documents {
			s := 0.0
			for _, w := range strings.Fields(strings.ToLower(req.Query)) {
				if strings.Contains(strings.ToLower(d), w) {
					s++
				}
			}
			out = append(out, res{i, s - 1}) // can be negative, like a logit
		}
		sort.SliceStable(out, func(a, b int) bool { return out[a].Score > out[b].Score })
		if req.TopN < len(out) {
			out = out[:req.TopN]
		}
		_ = json.NewEncoder(w).Encode(map[string]any{"model": "x", "object": "list",
			"usage": map[string]int{"prompt_tokens": 42, "total_tokens": 42}, "results": out})
	})
	return mux
}

func newTestServer(t *testing.T, backend Backend, ollama *fakeOllama) *httptest.Server {
	u, _ := url.Parse(ollama.URL)
	s := NewServer(backend, u)
	s.MaxDocs = 5
	s.LocalOnly = true
	ts := httptest.NewServer(s.Handler())
	t.Cleanup(ts.Close)
	return ts
}

func post(t *testing.T, url string, body any) (int, map[string]any) {
	t.Helper()
	b, _ := json.Marshal(body)
	resp, err := http.Post(url, "application/json", bytes.NewReader(b))
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	var out map[string]any
	_ = json.NewDecoder(resp.Body).Decode(&out)
	return resp.StatusCode, out
}

var docs = []any{"Paris is the capital of France.", map[string]string{"text": "Berlin is in Germany."}, "The capital of France is Paris, on the Seine."}

func TestRerankShapes(t *testing.T) {
	ollama := newFakeOllama(t)
	engine := httptest.NewServer(fakeEngineHandler(nil))
	defer engine.Close()
	ts := newTestServer(t, &StaticBackend{Base: engine.URL, Kind: ScoreProbability}, ollama)

	for _, path := range []string{"/v1/rerank", "/rerank", "/api/rerank", "/v1/reranking"} {
		code, out := post(t, ts.URL+path, map[string]any{"model": "m", "query": "capital of France", "documents": docs,
			"top_n": 2, "return_documents": true})
		if code != 200 {
			t.Fatalf("%s: %d %v", path, code, out)
		}
		results := out["results"].([]any)
		if len(results) != 2 {
			t.Fatalf("%s: top_n not applied: %v", path, results)
		}
		first := results[0].(map[string]any)
		if int(first["index"].(float64)) != 0 && int(first["index"].(float64)) != 2 {
			t.Fatalf("%s: wrong order %v", path, results)
		}
		doc := first["document"]
		if path == "/api/rerank" {
			if _, ok := doc.(string); !ok {
				t.Fatalf("Dify expects a string document, got %T", doc)
			}
		} else if _, ok := doc.(map[string]any)["text"]; !ok {
			t.Fatalf("%s: want document.text, got %v", path, doc)
		}
		if out["model"] != "m" || out["usage"].(map[string]any)["total_tokens"].(float64) != 42 {
			t.Fatalf("%s: bad envelope %v", path, out)
		}
	}
}

