func TestResolver(t *testing.T) {
	ollama := newFakeOllama(t)
	dir := t.TempDir()
	blobs := filepath.Join(dir, "blobs")
	_ = os.MkdirAll(blobs, 0o755)
	blob := filepath.Join(blobs, "sha256-"+strings.Repeat("ab", 32))
	_ = os.WriteFile(blob, []byte("GGUF"), 0o600)
	ollama.models["good:latest"] = blob
	ollama.models["elsewhere"] = "/somewhere/else/blobs/sha256-" + strings.Repeat("ab", 32)
	ollama.models["weird"] = "/etc/passwd"
	ollama.models["mlx"] = blob
	ollama.formats["mlx"] = "safetensors"

	r := &Resolver{Ollama: ollama.URL, Client: http.DefaultClient}
	ctx := context.Background()
	if p, err := r.Resolve(ctx, "good:latest"); err != nil || p != blob {
		t.Fatalf("good: %q %v", p, err)
	}
	if _, err := r.Resolve(ctx, "elsewhere"); err == nil || !strings.Contains(err.Error(), "--models-dir") {
		t.Fatalf("elsewhere without models dir: %v", err)
	}
	r.ModelsDir = dir
	if p, err := r.Resolve(ctx, "elsewhere"); err != nil || p != blob {
		t.Fatalf("elsewhere with models dir: %q %v", p, err)
	}
	if _, err := r.Resolve(ctx, "weird"); err == nil {
		t.Fatal("a non-blob path must be refused")
	}
	if _, err := r.Resolve(ctx, "mlx"); err == nil || !strings.Contains(err.Error(), "safetensors") {
		t.Fatalf("mlx: %v", err)
	}
	if _, err := r.Resolve(ctx, "missing"); err == nil || !strings.Contains(err.Error(), "ollama pull") {
		t.Fatalf("missing: %v", err)
	}
}

